export type AssetFormat =
  | (typeof FORMAT_CATEGORIES)[number]['options'][number]
  | keyof typeof LEGACY_FORMAT_LABELS;

export function normalizeAssetFormat(format: string): AssetFormat {
  return (LEGACY_FORMAT_LABELS[format as keyof typeof LEGACY_FORMAT_LABELS] ?? format) as AssetFormat;
}

export function isAssetFormat(format: unknown): format is AssetFormat {
  return typeof format === 'string' && (
    Object.hasOwn(LEGACY_FORMAT_LABELS, format)
    || FORMAT_CATEGORIES.some((category) => (category.options as readonly string[]).includes(format))
  );
}

export function requiresCustomAssetSpecs(format: string): boolean {
  return (CUSTOM_ASSET_FORMATS as readonly string[]).includes(format);
}
